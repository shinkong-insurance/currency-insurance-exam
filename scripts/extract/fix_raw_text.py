def apply_known_fixes(blocks: list[dict]) -> list[dict]:
    """回傳一份新的 blocks 清單，把已知有來源文字缺陷的幾筆 question_raw/
    explanation_raw 換成人工核對過的乾淨版本，其餘欄位不動。不修改傳入的
    原始清單（回傳新的 dict，不是原地修改）。"""
    fixed = []
    for b in blocks:
        key = (b["exam_set"], b["question_no"])
        if key in _QUESTION_RAW_FIXES or key in _EXPLANATION_RAW_FIXES:
            b = dict(b)
            if key in _QUESTION_RAW_FIXES:
                b["question_raw"] = _QUESTION_RAW_FIXES[key]
            if key in _EXPLANATION_RAW_FIXES:
                b["explanation_raw"] = _EXPLANATION_RAW_FIXES[key]
        fixed.append(b)
    return fixed
